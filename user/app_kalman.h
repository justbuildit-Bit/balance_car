#ifndef APP_KALMAN_H
#define APP_KALMAN_H
#include "stm32f10x.h"                  //只需要 uint8_t/uint16_t 这类定宽类型，不必引 math.h

/*
 * 卡尔曼滤波姿态融合（独立模块，不修改 app_MPU6050.c）
 * ============================================================
 * 上层用法：在 main 的 while(1) 里 App_MPU6050_Proc() 之后调用
 *           App_Kalman_Proc()，然后读 App_Kalman_GetPitch() 等。
 *           顺序不能反：Proc 里读的是"本周期的传感器值"，
 *           如果先跑卡尔曼，拿到的是上一周期的旧数据，等于凭空多 5ms 延迟。
 *
 * 数据来源：全部通过 App_MPU6050_GetAx/Ay/Az/Gx/Gy/Gz() 获取，
 *           不直接访问驱动的任何内部变量，也不改动互补滤波。
 *           这样做的好处：互补滤波和卡尔曼能并行跑、同一张图上对比，
 *           调卡尔曼时随时可以切回互补滤波当基准，不用改代码。
 *
 * 滤波器状态取 [角度, 陀螺零偏] 两个量：
 *   angle(k) = angle(k-1) + dt * ( rate(k) - bias(k-1) )
 *   bias(k)  = bias(k-1)
 *   z(k)     = angle(k) + v        （v 为加速度计解算角度的噪声）
 *
 * 相比互补滤波（固定权重 0.95238），卡尔曼的权重由协方差矩阵 P
 * 实时算出，并且附带把陀螺零偏估出来，抑制积分漂移。
 * ============================================================
 */

/* ------------------------------------------------------------
 * 三个噪声参数：整个滤波器只有这三个旋钮，其余都是推导出来的
 *
 * 【调参总原则】它们没有绝对正确的值，只有"匹配你的硬件"的值。
 *   判断标准永远是两条曲线的形状，不是数字本身：
 *     - 滤波结果太"粘"（推一下跟不上、回稳慢）→ 需要更快 → 增大 Q 或减小 R
 *     - 滤波结果太"毛"（静止时还在抖）        → 需要更稳 → 减小 Q 或增大 R
 *   现在 R=1 是猜的，正确做法见 KALMAN_R_MEASURE 下面的实测步骤。
 * ------------------------------------------------------------ */

/* 过程噪声：角度。越大越"相信陀螺"，跟随快但噪声大 */
/* 【原注释方向写反了，按下面实测表改正】
 * 过程噪声：角度。越大越"不信任陀螺的预测"，越依赖加速度计 → 跟随快、噪声大、滞后小。
 *
 * 为什么？Q 表达的是"我积分出来的角度有多不可靠"。Q 越大，协方差 P 涨得越快，
 * 卡尔曼增益 K = P/(P+R) 就越大，于是每一帧采信测量值的比例越高。
 * 实测（Q_bias=0.003, R=1, dt=5ms 下的稳态值）：
 *
 *      Q_ANGLE     稳态 K0     等效时间常数 τ     零偏估计标准差
 *      0.0001      0.0251      0.199 s           0.53 °/s     ← 很稳，但推车后回得慢
 *      0.001       0.0386      0.130 s           0.66 °/s     ← 当前值
 *      0.01        0.0976      0.051 s           1.06 °/s     ← 明显开始毛
 *      0.1         0.2708      0.018 s           1.86 °/s     ← 基本等于没滤波
 *
 * τ 的物理意义：滤波器追上真实角度大约需要 5τ。当前 0.13s，
 * 而你的平衡车振荡周期是 0.59s（1.7Hz）—— 滤波器滞后不到周期的 1/4，
 * 这是能接受的上限。再调慢它就会开始吃掉控制环的相位裕度。 */
#ifndef KALMAN_Q_ANGLE
#define KALMAN_Q_ANGLE      0.001f
#endif

/* 过程噪声：零偏。越大零偏收敛越快，但易把真实运动误判成零偏 */
/* 这个方向是对的，补充实测（Q_angle=0.001, R=1）：
 *
 *      Q_BIAS      K0        τ         零偏估计标准差
 *      0.0003      0.0337    0.148 s   0.34 °/s    ← 零偏几乎锁死，跟不了温漂
 *      0.003       0.0386    0.130 s   0.66 °/s    ← 当前值
 *      0.03        0.0509    0.098 s   1.35 °/s
 *      0.3         0.0773    0.065 s   2.97 °/s    ← 开始把车的真实倾斜当成零偏
 *
 * 调大的风险是"抢功能"：车持续往一边倒，滤波器会以为"是陀螺零偏在骗我"，
 * 于是猛调 bias 去抵消，结果把一个真实的倾角吃掉了。
 * 判据：静止时看 ch4 是否收敛；如果车在明显倾斜而 ch4 还在爬，说明 Q_bias 太大。 */
#ifndef KALMAN_Q_BIAS
#define KALMAN_Q_BIAS       0.003f
#endif

/* 量测噪声：加速度计解算角度的方差，单位 (°)²。 */
/* 建议实测：车静止时记录加速度计解算角的波动，算出标准差 σ，令 R = σ²。
 * 真实 MPU6050 通常落在 0.5 ~ 4 之间。
 *
 * 现在这个 1.0 是猜的，没有实测依据。怎么测（不用写代码）：
 *   1) 车静止放好，VOFA+ 只看 ch0（加速度计原始角），跑 10 秒；
 *   2) 看波形上下摆动的峰峰值，除以 6 约等于 σ（正态分布 99.7% 落在 ±3σ 内）；
 *   3) R = σ²。比如峰峰 6°，σ≈1°，R≈1 —— 正好对上当前的猜测值。
 *
 * R 的影响（Q_angle=0.001, Q_bias=0.003）：
 *      R        K0        τ          说明
 *      0.1      0.1026    0.049 s    加计非常准时
 *      1        0.0386    0.130 s    当前值
 *      10       0.0164    0.305 s    偏稳，推车后回得慢
 *      100      0.0080    0.624 s    只有陀螺在起作用
 *
 * 注意一个反直觉的点：R 填小了不会"更准"，只会"更抖"。
 * R 必须诚实反映真实噪声水平。填小了等于骗滤波器说"我的测量很准"，
 * 它就会过度采信噪声，输出反而更差。 */
#ifndef KALMAN_R_MEASURE
#define KALMAN_R_MEASURE    1.000f
#endif

/* 加速度模值门限：车体急加速/受撞击时 |a| 明显偏离 1g，此时
 * atan2 解算的角度不可信，只做预测不做校正。1=启用 0=关闭 */
/* 为什么默认关闭？因为推车测试时恰恰需要加速度计把车拉回来，
 * 关掉门控才能测出真实的抗扰响应。等上车做急停/急转时再打开。
 * 它的代价：门控命中期间滤波器退回纯积分，时间一长就会漂，
 * 所以不能长时间开启，只能当"短时间内挡住坏数据"用。 */
#ifndef KALMAN_ACC_GATE
#define KALMAN_ACC_GATE     0
#endif


/* ------------------------------------------------------------
 * 滤波器对象。所有状态都在这里，没有任何隐藏的全局量，
 * 所以同一个结构体可以复制多份、并行跑多个滤波器做 A/B 对比。
 * ------------------------------------------------------------ */
typedef struct
{
	float angle;        //融合后的角度估计，单位 °
	                    //初始化时用加速度计角度，之后全靠递推，不再被直接赋值

	float bias;         //陀螺零偏估计，单位 °/s
	                    //注意这是"残余零偏"：进滤波器前 gx 已经扣过 gx_offset，
	                    //所以收敛值 ≈ -(gx_offset)，两者相加才是总零偏。
	                    //这个符号关系可以用来检查通道有没有接错

	float rate;         //去掉零偏后的角速度，单位 °/s
	                    //它本是 Predict 里的中间量，但控制环内环正好需要它，
	                    //所以留成公开状态：省掉上层再算一遍减法

	float P[2][2];      //状态估计误差协方差矩阵
	                    //P[0][0] 角度方差 (°)²     —— 决定 K0，也就是"听加计多少"
	                    //P[1][1] 零偏方差 (°/s)²   —— 决定零偏能多快跟着变
	                    //P[0][1] 角度与零偏的协方差 —— 这一项是负的，负号让 K1<0，
	                    //   从而"角度偏小 → 零偏调小"这个修正在数学上自动成立，
	                    //   不需要人手动推因果方向。整个滤波器的"智能"就在这里
	                    //矩阵必须保持对称（P[0][1] == P[1][0]）且正定；
	                    //一旦因写错更新顺序而失去对称性，几步之内就会发散

	float Q_angle;      //角度过程噪声，单位 (°)²/s（连续时间密度，代码里乘 dt 使用）
	float Q_bias;       //零偏过程噪声，单位 (°/s)²/s
	float R_measure;    //量测噪声，单位 (°)²
	                    //三个参数放实例里而不是直接用宏：可以"俯仰一套、翻滚另一套"，
	                    //也可以运行时扫描参数做对比实验，不用重新编译
} Kalman_t;


/* ---------- 通用卡尔曼算法（可用于任意"角度+零偏"场景） ---------- */
/* 这四个函数与 MPU6050 完全无关，只操作 Kalman_t。
 * 换传感器（ICM20948、BMI088）只要改下面的姿态融合层，这四个函数一行都不用动。 */
void  App_Kalman_Init(Kalman_t *kf, float initAngle);
void  App_Kalman_Predict(Kalman_t *kf, float rateMeasure, float dt);
float App_Kalman_Correct(Kalman_t *kf, float angleMeasure);
float App_Kalman_Update(Kalman_t *kf, float angleMeasure, float rateMeasure, float dt, uint8_t useMeasure);

/* ---------- 姿态融合层（与 MPU6050 驱动对接） ---------- */
void  App_Kalman_Proc(void);                     //每 5ms 跑一次，内部自己做节拍
void  App_Kalman_GyroCalibrate(uint16_t samples); //上电静止调用，阻塞约 samples 毫秒

float App_Kalman_GetPitch(void);                 //融合角，控制环的 theta 用它
float App_Kalman_GetRoll(void);                  //目前控制环不用，留着画图和以后做侧向平衡
float App_Kalman_GetYaw(void);                   //纯积分，只能看相对转角，不能当绝对方位

/* 加速度计直接解算的角度（未滤波）。噪声大，用于和滤波结果对照观察，
 * 也可以用 VOFA+ 画在同一个波形图里看滤波器的抑制效果。
 * 调 Q/R 时这是唯一能判断"滤过头了没有"的参考线：
 * 如果滤波结果比它滞后半个振荡周期以上，就是滤过头了。 */
float App_Kalman_GetAccelPitch(void);
float App_Kalman_GetAccelRoll(void);

float App_Kalman_GetPitchBias(void);             //ch4，看零偏收敛过程
float App_Kalman_GetRollBias(void);

/* 上电标定得到的 x 轴陀螺零偏，单位°/s。
 * 只被卡尔曼通道扣掉；互补滤波用原始 gx，所以它的稳态偏差 ≈ 该值 × 0.1s。 */
float App_Kalman_GetGyroOffset(void);            //ch3，和 ch4 一起做零偏对账

/* 已去掉零偏的角速度，可直接给控制环做 D 项和转向反馈。
 * GetPitchRate 减的是"标定零偏 + 滤波器估计的 bias"，比原始 gx 干净；
 * GetYawRate 减的是标定时测到的 gz 零偏（未标定时等于原始 gz）。 */
float App_Kalman_GetPitchRate(void);
float App_Kalman_GetYawRate(void);

#endif
